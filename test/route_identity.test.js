/**
 * Route identity across a save and load.
 *
 * A saved project names each route. The first implementation preserved those
 * ids in the file and lost them on the way back in: `applyProject` rebuilt every
 * route through `createRoute()` without passing the id, so a freshly loaded page
 * somewhere in the middle of the id sequence silently renumbered the restored
 * rows. Nothing broke until something addressed a route by id - selecting a row,
 * editing it, deleting it - and then the wrong route was affected.
 *
 * These tests exercise the real thing: a project is serialised, parsed, and
 * applied through the same `applyProject` logic the browser runs, and the ids are
 * checked before and after each operation that could disturb them.
 */

import assert from 'node:assert/strict';
import test from 'node:test';

import {
  createRoute,
  createState,
  nextRouteId,
  reserveRouteId,
} from '../src/ui/state.js';
import { parseProjectJson, serializeProjectJson } from '../src/ui/project.js';

const FIXED_DATE = new Date('2026-07-08T09:10:11.000Z');

/**
 * Hydrate a project the way `applyProject` does.
 *
 * Mirrors the assignment in `app.js` so the identity rules can be tested without
 * a DOM. `test/recovery.test.js` and the browser harness pin that `app.js`
 * performs this same mapping, including passing `id`.
 *
 * @param {object} project Validated project.
 * @returns {object} Fresh app state.
 */
function applyProjectToState(project) {
  const state = createState();
  state.routes = project.routes.map((route) =>
    createRoute({
      id: route.id,
      from: route.from,
      direction: route.direction,
      spans: route.spans,
      tc: route.tc,
      fpb: route.fpb,
    }),
  );
  state.originMarker = project.originMarker;
  state.spanLength = project.spanLength;
  state.layout = project.layout;
  state.selectedId = null;
  return state;
}

/** A project whose route ids are memorable and deliberately non-sequential. */
function identifiedProject() {
  return {
    routes: [
      { id: 'route-101', from: 'origin', direction: 'south', spans: 2, tc: false, fpb: false },
      { id: 'route-102', from: 'endpoint:A', direction: 'east', spans: 3, tc: false, fpb: false },
      { id: 'route-103', from: 'origin', direction: 'west', spans: 1, tc: true, fpb: false },
      { id: 'route-104', from: 'origin', direction: 'north', spans: 2, tc: false, fpb: true },
    ],
    originMarker: 'plain',
    spanLength: 40,
    layout: 'a4_landscape',
  };
}

/** Round trip through the real file format. */
function reload(project) {
  const text = serializeProjectJson(project, { now: FIXED_DATE });
  const parsed = parseProjectJson(text);
  assert.equal(parsed.ok, true, 'the project survives the round trip');
  return parsed.project;
}

test('1. every restored route keeps its saved id', () => {
  const original = identifiedProject();
  const state = applyProjectToState(reload(original));
  assert.deepEqual(
    state.routes.map((r) => r.id),
    ['route-101', 'route-102', 'route-103', 'route-104'],
  );
  // Position and content are preserved with the id.
  assert.equal(state.routes.length, original.routes.length);
  assert.deepEqual(
    state.routes.map((r) => r.from),
    ['origin', 'endpoint:A', 'origin', 'origin'],
  );
});

test('2. ids are not regenerated by a successful import', () => {
  // A page whose generator has never produced anything is the worst case: the
  // old code would have handed out route-1, route-2, ... to a restored project.
  const state = applyProjectToState(reload(identifiedProject()));
  for (const route of state.routes) {
    assert.doesNotMatch(
      route.id,
      /^route-[1-4]$/,
      `${route.id} is the saved id, not a regenerated one`,
    );
  }
});

test('3. the id generator cannot produce an id a restored route already uses', () => {
  applyProjectToState(reload(identifiedProject()));
  // The highest restored number was 104, so the next generated id must be above
  // it, never a value that a restored route holds.
  const next = nextRouteId();
  assert.equal(next, 'route-105');

  const restoredIds = new Set(['route-101', 'route-102', 'route-103', 'route-104']);
  for (let i = 0; i < 20; i += 1) {
    const id = createRoute({ from: 'origin' }).id;
    assert.ok(!restoredIds.has(id), `${id} does not collide with a restored route`);
  }
});

test('4. a reserved id raises the counter without creating a second id space', () => {
  assert.equal(reserveRouteId('route-900'), 'route-900');
  const next = nextRouteId();
  assert.equal(next, 'route-901');
  // Restored ids that are not of the generated form are kept as they are and do
  // not disturb the counter.
  assert.equal(reserveRouteId('custom-id'), 'custom-id');
  assert.equal(nextRouteId(), 'route-902');
});

test('5. editing one restored route does not touch another', () => {
  const state = applyProjectToState(reload(identifiedProject()));
  const before = state.routes.map((r) => ({ ...r }));

  // The selection and edit path used by the table: find by id, replace by id.
  state.selectedId = 'route-102';
  const index = state.routes.findIndex((r) => r.id === state.selectedId);
  assert.ok(index >= 0, 'the restored id addresses exactly one row');
  state.routes[index] = { ...state.routes[index], spans: 9 };

  // Everything else is untouched, id included.
  for (const [i, route] of state.routes.entries()) {
    if (route.id === 'route-102') {
      assert.equal(route.spans, 9, 'the edited row changed');
      continue;
    }
    assert.deepEqual(route, before[i], `${route.id} is unchanged by another row's edit`);
  }
  assert.deepEqual(
    state.routes.map((r) => r.id),
    ['route-101', 'route-102', 'route-103', 'route-104'],
  );
});

test('6. adding a route after an import does not collide', () => {
  const state = applyProjectToState(reload(identifiedProject()));
  const added = createRoute({ from: 'origin', direction: 'east', spans: 1 });
  state.routes.push(added);

  const ids = state.routes.map((r) => r.id);
  assert.equal(new Set(ids).size, ids.length, 'all ids are distinct');
  // The counter is shared across the run, so the exact number is not fixed; the
  // requirement is that the new route is above every restored one and unique.
  assert.ok(!['route-101', 'route-102', 'route-103', 'route-104'].includes(ids.at(-1)));
});

test('7. deleting a route leaves every other identity stable', () => {
  const state = applyProjectToState(reload(identifiedProject()));
  const index = state.routes.findIndex((r) => r.id === 'route-102');
  state.routes.splice(index, 1);

  assert.deepEqual(
    state.routes.map((r) => r.id),
    ['route-101', 'route-103', 'route-104'],
    'the surviving routes keep their ids',
  );
  // The id that was removed is not handed out again.
  assert.ok(!state.routes.some((r) => r.id === 'route-102'));
  assert.notEqual(nextRouteId(), 'route-102');
});

test('8. a selection survives when an unrelated route is deleted', () => {
  const state = applyProjectToState(reload(identifiedProject()));
  state.selectedId = 'route-104';
  const index = state.routes.findIndex((r) => r.id === 'route-101');
  state.routes.splice(index, 1);

  assert.ok(
    state.routes.some((r) => r.id === state.selectedId),
    'the selected route is still selectable after deleting a different one',
  );
});

test('9. two saved projects loaded in sequence do not share identities', () => {
  const first = applyProjectToState(reload(identifiedProject()));
  const second = applyProjectToState(
    reload({
      ...identifiedProject(),
      routes: [
        { id: 'route-7', from: 'origin', direction: 'north', spans: 1, tc: false, fpb: false },
        { id: 'route-8', from: 'endpoint:A', direction: 'east', spans: 1, tc: false, fpb: false },
      ],
    }),
  );

  assert.deepEqual(first.routes.map((r) => r.id), [
    'route-101',
    'route-102',
    'route-103',
    'route-104',
  ]);
  assert.deepEqual(second.routes.map((r) => r.id), ['route-7', 'route-8']);

  // The generator is past both sets, so a new route cannot reuse either.
  const next = nextRouteId();
  assert.ok(!['route-7', 'route-8', 'route-101'].includes(next), `${next} is fresh`);
});

test('10. endpoint identity is unaffected by route id preservation', () => {
  const project = identifiedProject();
  const state = applyProjectToState(reload(project));
  // Routes still reference the same source endpoints, by endpoint id.
  assert.equal(state.routes[1].from, 'endpoint:A', 'a route still starts from A');
  assert.deepEqual(
    state.routes.map((r) => r.from),
    project.routes.map((r) => r.from),
    'no source endpoint was rewritten',
  );
});

test('11. app.js passes the saved id when it hydrates a project', async () => {
  // The mapping in the test above must match the app, so the app is checked for
  // the `id:` field it has to pass.
  const { readFileSync } = await import('node:fs');
  const source = readFileSync(new URL('../src/ui/app.js', import.meta.url), 'utf8');
  const body = source.slice(
    source.indexOf('function applyProject'),
    source.indexOf('function restoreOrStart'),
  );
  assert.match(body, /createRoute\(\{\s*\n\s*id: route\.id,/, 'applyProject passes the saved id');
});
